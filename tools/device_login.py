#!/usr/bin/env python3
"""One-time OAuth login for the CYD, independent of the PC's Claude Code login.

Runs the same PKCE flow as `claude /login`, then writes the resulting token pair
into the git-ignored src/secrets.h, together with the Wi-Fi credentials. The board
then rotates its own tokens, so it no longer shares a refresh-token chain with the PC.
"""
import base64, getpass, hashlib, json, re, secrets, sys, time, urllib.parse, urllib.request
from pathlib import Path

CLIENT_ID = "9d1c250a-e61b-44d9-88ed-5944d1962f5e"
AUTHORIZE = "https://claude.com/cai/oauth/authorize"
TOKEN_URL = "https://platform.claude.com/v1/oauth/token"
REDIRECT = "https://platform.claude.com/oauth/code/callback"
SCOPES = "user:profile user:inference user:sessions:claude_code user:mcp_servers"
TEMPLATE = '''#pragma once
// Generated by tools/device_login.py. Git-ignored: never commit this file.
// Tokens are only the initial seed; after the first refresh the board keeps
// the rotated tokens in NVS.
#define WIFI_SSID "{ssid}"
#define WIFI_PASS "{wifi_pass}"
#define SEED_ACCESS_TOKEN  "{access}"
#define SEED_REFRESH_TOKEN "{refresh}"
#define SEED_EXPIRES_AT_MS {expires}LL
'''
SECRETS = Path(__file__).resolve().parent.parent / "src" / "secrets.h"


def ask_wifi():
    """Prompt for Wi-Fi credentials, defaulting to the ones already in secrets.h."""
    old = SECRETS.read_text() if SECRETS.exists() else ""
    def prev(name):
        m = re.search(rf'#define {name}\s+"(.*)"', old)
        return m.group(1) if m else ""
    ssid = input(f"Wi-Fi SSID [{prev('WIFI_SSID')}]: ").strip() or prev("WIFI_SSID")
    pw = getpass.getpass("Wi-Fi password [keep current]: ") or prev("WIFI_PASS")
    if not ssid:
        sys.exit("Wi-Fi SSID is required")
    return ssid, pw


def b64(b):
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def main():
    verifier = b64(secrets.token_bytes(32))
    challenge = b64(hashlib.sha256(verifier.encode()).digest())
    state = b64(secrets.token_bytes(32))
    url = AUTHORIZE + "?" + urllib.parse.urlencode({
        "code": "true", "client_id": CLIENT_ID, "response_type": "code",
        "redirect_uri": REDIRECT, "scope": SCOPES,
        "code_challenge": challenge, "code_challenge_method": "S256", "state": state})
    ssid, wifi_pass = ask_wifi()
    print("\nOpen this URL in your browser, authorize, and paste the code shown:\n")
    print(url, "\n")
    pasted = input("Code: ").strip()
    code, _, got_state = pasted.partition("#")
    if got_state and got_state != state:
        sys.exit("state mismatch, aborting")

    body = json.dumps({"grant_type": "authorization_code", "code": code,
                       "redirect_uri": REDIRECT, "client_id": CLIENT_ID,
                       "code_verifier": verifier, "state": state}).encode()
    req = urllib.request.Request(TOKEN_URL, body, {"Content-Type": "application/json", "User-Agent": "claude-code/2.0"})
    try:
        tok = json.load(urllib.request.urlopen(req, timeout=20))
    except urllib.error.HTTPError as e:
        sys.exit(f"token exchange failed: {e.code} {e.read().decode()}")

    expires_ms = int(time.time() * 1000) + int(tok["expires_in"]) * 1000
    SECRETS.write_text(TEMPLATE.format(
        ssid=ssid, wifi_pass=wifi_pass, access=tok["access_token"],
        refresh=tok["refresh_token"], expires=expires_ms))
    print(f"\nOK: wrote device tokens to {SECRETS} (scope: {tok.get('scope')})")
    print("Now run: pio run -t erase && pio run -t upload")


if __name__ == "__main__":
    main()
